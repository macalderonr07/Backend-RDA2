   pem_punto               CHAR(3 CHAR)    NOT NULL,
   pem_descripcion         VARCHAR2(60 CHAR) NOT NULL,
   pem_activo              NUMBER(1)       DEFAULT 1 NOT NULL
      CONSTRAINT ckb_pem_activo CHECK (pem_activo IN (0, 1)),
   CONSTRAINT pk_punto_emision PRIMARY KEY (id_punto_emision),
   CONSTRAINT ak_punto_emision_serie UNIQUE (pem_establecimiento, pem_punto)
