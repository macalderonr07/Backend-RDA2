COMMENT ON TABLE produccion.valor_atributo IS 'Valores permitidos de cada atributo (Negro, Café, 1.2 mm...).';

CREATE TABLE produccion.producto (
   id_producto             NUMBER(10)      GENERATED BY DEFAULT ON NULL AS IDENTITY,
   id_categoria            NUMBER(10)      NOT NULL,
   id_unidad_medida        VARCHAR2(4 CHAR) NOT NULL,
   id_tarifa_iva           VARCHAR2(2 CHAR) NOT NULL,
   prd_codigo              VARCHAR2(20 CHAR) NOT NULL,
   prd_nombre              VARCHAR2(150 CHAR) NOT NULL,
   prd_descripcion         CLOB            NULL,
