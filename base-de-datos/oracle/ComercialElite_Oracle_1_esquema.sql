   emp_ruc                 CHAR(13 CHAR)   NOT NULL,
   emp_razon_social        VARCHAR2(150 CHAR) NOT NULL,
   emp_nombre_comercial    VARCHAR2(100 CHAR) NOT NULL,
   emp_eslogan             VARCHAR2(150 CHAR) NULL,
   emp_correo              VARCHAR2(120 CHAR) NOT NULL,
   emp_telefono            VARCHAR2(15 CHAR) NULL,
   id_direccion_matriz     NUMBER(10)      NOT NULL,
   emp_dias_devolucion     NUMBER(5)       DEFAULT 30 NOT NULL
      CONSTRAINT ckc_emp_dias_devolucion CHECK (emp_dias_devolucion > 0),
   emp_ambiente_sri        CHAR(1 CHAR)    DEFAULT '1' NOT NULL
