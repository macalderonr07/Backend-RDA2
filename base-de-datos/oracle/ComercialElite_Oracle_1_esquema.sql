/*==============================================================*/
/* COMERCIAL ELITE - Modelo físico (versión Oracle 19c / 21c)   */
/* 1. ESQUEMA: usuarios de cada nodo, tablas, claves, CHECK,    */
/*    índices y comentarios. Equivale a ComercialElite_PDM.sql  */
/*    de PostgreSQL.                                            */
/*                                                              */
/* Cómo se ejecuta: conectado como SYSTEM (o un DBA) a la PDB   */
/* donde vivirá la base, por ejemplo:                           */
/*    sqlplus system@//localhost:1521/XEPDB1 @ComercialElite_Oracle_0_instalar.sql */
/* (el instalador corre los scripts 1, 2 y 3 en orden).         */
/*                                                              */
/* Diferencias con PostgreSQL                                   */
/*   - Cada nodo es un usuario (esquema): PRODUCCION y          */
/*     ECOMMERCE. Mañana cada uno pasa a su propia PDB.         */
/*   - SERIAL -> NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY*/
/*   - BOOLEAN -> NUMBER(1) con CHECK (0, 1)                    */
/*   - TEXT -> CLOB; VARCHAR(n) -> VARCHAR2(n CHAR)             */
/*   - Índices únicos parciales -> índices por expresión        */
/*==============================================================*/

-- Para volver a empezar desde cero (borra todo lo de los dos nodos):
--   DROP USER ecommerce CASCADE;
--   DROP USER produccion CASCADE;

SET DEFINE OFF
SET SQLBLANKLINES ON
WHENEVER SQLERROR EXIT FAILURE

/*==============================================================*/
/* 0. USUARIOS (uno por nodo)                                   */
/*    Las contraseñas NO van en el script: sqlplus las pide al  */
/*    correrlo, o se definen antes de llamarlo:                 */
/*      DEFINE clave_produccion = "..."                         */
/*      DEFINE clave_ecommerce  = "..."                         */
/*==============================================================*/
SET DEFINE ON
SET VERIFY OFF
CREATE USER produccion IDENTIFIED BY "&&clave_produccion" DEFAULT TABLESPACE users QUOTA UNLIMITED ON users;
CREATE USER ecommerce  IDENTIFIED BY "&&clave_ecommerce"  DEFAULT TABLESPACE users QUOTA UNLIMITED ON users;
SET DEFINE OFF
GRANT CREATE SESSION, CREATE TABLE, CREATE VIEW, CREATE PROCEDURE, CREATE TRIGGER, CREATE SEQUENCE, CREATE TYPE
   TO produccion, ecommerce;



