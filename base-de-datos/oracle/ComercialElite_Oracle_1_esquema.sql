   usu_hash_clave          VARCHAR2(255 CHAR) NOT NULL,
   usu_activo              NUMBER(1)       DEFAULT 1 NOT NULL
      CONSTRAINT ckb_usu_activo CHECK (usu_activo IN (0, 1)),
   usu_creado              TIMESTAMP       DEFAULT LOCALTIMESTAMP NOT NULL,
   usu_ultimo_acceso       TIMESTAMP       NULL,
