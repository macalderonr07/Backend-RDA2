/*==============================================================*/

CREATE TABLE produccion.usuario (
   id_usuario              NUMBER(10)      GENERATED BY DEFAULT ON NULL AS IDENTITY,
   usu_correo              VARCHAR2(120 CHAR) NOT NULL
