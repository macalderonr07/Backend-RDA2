/*==============================================================*/
/* Migracion: SECTOR en datos de facturacion y direcciones      */
/*                                                              */
/* Regla del negocio: al facturar, el SECTOR es obligatorio y   */
/* la direccion es opcional. Toda direccion pertenece a un      */
/* sector de su misma ciudad.                                   */
/*  - sector (id_ciudad, nombre): se crea al registrar datos de */
/*    facturacion o direcciones si aun no existe.               */
/*  - datos_facturacion.id_sector: obligatorio en los NUEVOS    */
/*    (trigger); si no se indica pero hay direccion, se toma el */
/*    de la direccion. Consumidor final (07) no lo necesita.    */
/*  - direccion.id_sector: obligatorio en las nuevas y de la    */
/*    misma ciudad (trigger).                                   */
/*  Los registros anteriores quedan sin sector (no se inventa). */
/*                                                              */
/* Se puede correr mas de una vez.                              */
/*==============================================================*/
SET DEFINE OFF
WHENEVER SQLERROR EXIT FAILURE ROLLBACK
ALTER SESSION SET CURRENT_SCHEMA = produccion;

DECLARE
    v_n NUMBER;
    PROCEDURE ddl(p_sql VARCHAR2) IS BEGIN EXECUTE IMMEDIATE p_sql; END;
BEGIN
    SELECT COUNT(*) INTO v_n FROM all_tables WHERE owner = 'PRODUCCION' AND table_name = 'SECTOR';
    IF v_n = 0 THEN
        ddl(q'[CREATE TABLE produccion.sector (
                  id_sector  NUMBER GENERATED BY DEFAULT AS IDENTITY,
                  id_ciudad  NUMBER NOT NULL,
                  sec_nombre VARCHAR2(80 CHAR) NOT NULL,
                  sec_activo NUMBER(1) DEFAULT 1 NOT NULL,
                  CONSTRAINT pk_sector PRIMARY KEY (id_sector),
                  CONSTRAINT fk_sector_ciudad FOREIGN KEY (id_ciudad) REFERENCES produccion.ciudad (id_ciudad),
                  CONSTRAINT ck_sector_activo CHECK (sec_activo IN (0, 1)),
                  CONSTRAINT ck_sector_nombre CHECK (TRIM(sec_nombre) IS NOT NULL))]');
        -- un nombre por ciudad, sin distinguir mayusculas ni tildes
        ddl(q'[CREATE UNIQUE INDEX produccion.ak_sector_ciudad_nombre ON produccion.sector (id_ciudad, NLSSORT(TRIM(sec_nombre), 'NLS_SORT=BINARY_AI'))]');
        ddl(q'[COMMENT ON TABLE produccion.sector IS 'Sector (barrio) de una ciudad: obligatorio en los datos de facturacion y en toda direccion']');
    END IF;
    SELECT COUNT(*) INTO v_n FROM all_tab_columns WHERE owner = 'PRODUCCION' AND table_name = 'DATOS_FACTURACION' AND column_name = 'ID_SECTOR';
    IF v_n = 0 THEN
        ddl('ALTER TABLE produccion.datos_facturacion ADD (id_sector NUMBER CONSTRAINT fk_dfa_sector REFERENCES produccion.sector (id_sector))');
        ddl('CREATE INDEX produccion.ix_dfa_sector ON produccion.datos_facturacion (id_sector)');
    END IF;
    SELECT COUNT(*) INTO v_n FROM all_tab_columns WHERE owner = 'PRODUCCION' AND table_name = 'DIRECCION' AND column_name = 'ID_SECTOR';
    IF v_n = 0 THEN
        ddl('ALTER TABLE produccion.direccion ADD (id_sector NUMBER CONSTRAINT fk_direccion_sector REFERENCES produccion.sector (id_sector))');
        ddl('CREATE INDEX produccion.ix_direccion_sector ON produccion.direccion (id_sector)');
    END IF;
END;
/

-- Sectores de Quito para empezar (se agregan mas al registrar clientes)
DECLARE
    v_quito NUMBER;
BEGIN
    SELECT MIN(id_ciudad) INTO v_quito FROM ciudad WHERE UPPER(ciu_nombre) = 'QUITO';
    IF v_quito IS NOT NULL THEN
        FOR s IN (SELECT column_value AS nombre FROM TABLE(SYS.ODCIVARCHAR2LIST(
                      'Centro Histórico', 'La Mariscal', 'Iñaquito', 'Carcelén', 'Cotocollao', 'El Condado',
                      'La Magdalena', 'Chillogallo', 'Quitumbe', 'Solanda', 'Cumbayá', 'Tumbaco', 'Conocoto', 'Calderón'))) LOOP
            MERGE INTO sector x
            USING (SELECT v_quito AS id_ciudad, s.nombre AS nombre FROM dual) n
            ON (x.id_ciudad = n.id_ciudad AND NLSSORT(TRIM(x.sec_nombre), 'NLS_SORT=BINARY_AI') = NLSSORT(TRIM(n.nombre), 'NLS_SORT=BINARY_AI'))
            WHEN NOT MATCHED THEN INSERT (id_ciudad, sec_nombre) VALUES (n.id_ciudad, n.nombre);
        END LOOP;
    END IF;
    COMMIT;
END;
/

-- Toda direccion NUEVA lleva sector, y de su misma ciudad
CREATE OR REPLACE TRIGGER tr_direccion_sector
BEFORE INSERT OR UPDATE OF id_sector, id_ciudad ON direccion
FOR EACH ROW
DECLARE
    v_ciudad NUMBER;
BEGIN
    IF :NEW.id_sector IS NULL THEN
        IF INSERTING THEN
            pr_error('La dirección necesita su sector');
        END IF;
        RETURN;
    END IF;
    SELECT MAX(id_ciudad) INTO v_ciudad FROM sector WHERE id_sector = :NEW.id_sector;
    IF v_ciudad IS NULL THEN
        pr_error('El sector ' || :NEW.id_sector || ' no existe');
    ELSIF v_ciudad <> :NEW.id_ciudad THEN
        pr_error('El sector no pertenece a la ciudad de la dirección');
    END IF;
END;
/

-- Datos de facturacion NUEVOS: sector obligatorio (salvo consumidor final);
-- si no viene y hay direccion, se toma el de la direccion
CREATE OR REPLACE TRIGGER tr_datos_facturacion_sector
BEFORE INSERT OR UPDATE OF id_sector, id_direccion ON datos_facturacion
FOR EACH ROW
DECLARE
    v_sector NUMBER;
BEGIN
    IF :NEW.id_sector IS NULL AND :NEW.id_direccion IS NOT NULL THEN
        SELECT MAX(id_sector) INTO v_sector FROM direccion WHERE id_direccion = :NEW.id_direccion;
        :NEW.id_sector := v_sector;
    END IF;
    IF :NEW.id_sector IS NULL AND INSERTING AND :NEW.id_tipo_identificacion <> '07' THEN
        pr_error('Los datos de facturación necesitan el sector');
    END IF;
END;
/

/* Busca o crea un sector de una ciudad (sin distinguir mayusculas ni tildes). */
CREATE OR REPLACE FUNCTION fn_sector(p_ciudad IN NUMBER, p_nombre IN VARCHAR2) RETURN NUMBER IS
    v_id     NUMBER;
    v_nombre VARCHAR2(80 CHAR) := REGEXP_REPLACE(TRIM(p_nombre), '\s+', ' ');
BEGIN
    IF v_nombre IS NULL THEN
        pr_error('Escribe el sector');
    END IF;
    SELECT MIN(id_sector) INTO v_id FROM sector
    WHERE id_ciudad = p_ciudad AND NLSSORT(TRIM(sec_nombre), 'NLS_SORT=BINARY_AI') = NLSSORT(v_nombre, 'NLS_SORT=BINARY_AI');
    IF v_id IS NULL THEN
        INSERT INTO sector (id_ciudad, sec_nombre) VALUES (p_ciudad, v_nombre) RETURNING id_sector INTO v_id;
    END IF;
    RETURN v_id;
END fn_sector;
/

