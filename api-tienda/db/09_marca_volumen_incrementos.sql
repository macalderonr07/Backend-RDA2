-- Catalogo: + marca, incremento de venta y factor (columnas nuevas al final)
CREATE OR REPLACE VIEW v_catalogo AS
SELECT p.id_producto,
       p.prd_codigo,
       p.prd_nombre,
       c.cat_nombre                                            AS categoria,
       v.id_variante,
       v.var_sku,
       (SELECT LISTAGG(a.atr_nombre || ': ' || va.val_valor, ', ') WITHIN GROUP (ORDER BY a.atr_nombre)
        FROM variante_valor vv
        JOIN valor_atributo va ON va.id_valor_atributo = vv.id_valor_atributo
        JOIN atributo       a  ON a.id_atributo        = vv.id_atributo
        WHERE vv.id_variante = v.id_variante)                  AS caracteristicas,
       pr.id_presentacion,
       pr.pre_descripcion                                      AS presentacion,
       pr.pre_cantidad_minima                                  AS cantidad_minima,
       pv.precio,
       t.tiv_porcentaje                                        AS iva_porcentaje,
       ROUND(pv.precio * (1 + t.tiv_porcentaje / 100), 2)      AS precio_con_iva,
       ov.id_oferta,
       ov.ofe_porcentaje                                       AS pct_oferta,
       ov.ofe_hasta                                            AS oferta_hasta,
       ROUND(pv.precio * (1 - NVL(ov.ofe_porcentaje, 0) / 100), 2) AS precio_final,
       ROUND(ROUND(pv.precio * (1 - NVL(ov.ofe_porcentaje, 0) / 100), 2)
             * (1 + t.tiv_porcentaje / 100), 2)                AS precio_final_con_iva,
       -- en productos por pieza, lo máximo que se puede pedir en una línea
       -- es lo que tiene la pieza más grande
       FLOOR(GREATEST(CASE WHEN p.prd_venta_por_pieza = 1
                           THEN LEAST(s.disponible, NVL((SELECT MAX(ls.saldo) FROM v_lote_saldo ls
                                                         WHERE ls.id_variante = v.id_variante), 0))
                           ELSE s.disponible END, 0) / pr.pre_factor) AS disponible,
       CASE WHEN p.prd_fecha_creacion >= TRUNC(SYSDATE) - 30 THEN 1 ELSE 0 END AS es_novedad,
       -- datos de vitrina para el e-commerce
       p.prd_imagen_url                                        AS imagen_url,
       p.prd_uso                                               AS uso,
       c.cat_codigo                                            AS categoria_codigo,
       NVL(cp.cat_codigo, c.cat_codigo)                        AS linea_codigo,
       NVL(cp.cat_nombre, c.cat_nombre)                        AS linea,
       p.prd_fecha_creacion                                    AS fecha_creacion,
       p.id_unidad_medida                                      AS unidad_codigo,
       um.umd_nombre                                           AS unidad,
       p.prd_venta_por_pieza                                   AS venta_por_pieza,
       m.mar_nombre                                            AS marca,
       pr.pre_incremento                                       AS incremento,
       pr.pre_factor                                           AS factor
FROM producto p
JOIN categoria         c  ON c.id_categoria     = p.id_categoria
LEFT JOIN categoria    cp ON cp.id_categoria    = c.id_categoria_padre
LEFT JOIN marca        m  ON m.id_marca         = p.id_marca AND m.mar_activa = 1
JOIN unidad_medida     um ON um.id_unidad_medida = p.id_unidad_medida
JOIN tarifa_iva        t  ON t.id_tarifa_iva    = p.id_tarifa_iva
JOIN variante          v  ON v.id_producto      = p.id_producto
JOIN presentacion      pr ON pr.id_variante     = v.id_variante
JOIN v_precio_vigente  pv ON pv.id_presentacion = pr.id_presentacion
JOIN v_stock_variante  s  ON s.id_variante      = v.id_variante
LEFT JOIN v_oferta_vigente ov ON ov.id_producto = p.id_producto
WHERE p.prd_publicado = 1 AND v.var_activa = 1 AND pr.pre_activa = 1 AND c.cat_activa = 1;

-- Descuentos por volumen vigentes de los productos publicados (tienda)
CREATE OR REPLACE VIEW v_descuento_volumen_web AS
SELECT p.prd_codigo,
       dv.dvo_cantidad_minima                                  AS cantidad_minima,
       dv.dvo_porcentaje                                       AS porcentaje,
       p.id_unidad_medida                                      AS unidad_codigo,
       um.umd_nombre                                           AS unidad
FROM descuento_volumen dv
JOIN producto p       ON p.id_producto       = dv.id_producto
JOIN unidad_medida um ON um.id_unidad_medida = p.id_unidad_medida
WHERE dv.dvo_activo = 1 AND p.prd_publicado = 1;

-- Combos: una fila por combo x componente x variante publicada de ese
-- componente (con la forma de venta pedida). La API agrupa por color y ofrece
-- los colores que tienen stock en TODOS los componentes.
CREATE OR REPLACE VIEW v_combo_web AS
SELECT c.cmb_codigo                                            AS codigo,
       c.cmb_nombre                                            AS nombre,
       c.cmb_descripcion                                       AS descripcion,
       (SELECT COUNT(*) FROM combo_componente x WHERE x.id_combo = c.id_combo) AS componentes,
       v.prd_codigo,
       v.prd_nombre,
       cc.cco_presentacion                                     AS presentacion,
       cc.cco_cantidad                                         AS cantidad,
       v.id_presentacion,
       v.caracteristicas,
       v.precio_final_con_iva,
       v.disponible,
       v.imagen_url
FROM combo c
JOIN combo_componente cc ON cc.id_combo   = c.id_combo
JOIN v_catalogo       v  ON v.id_producto = cc.id_producto AND v.presentacion = cc.cco_presentacion
WHERE c.cmb_publicado = 1;

-- Para la futura administracion: proveedores que trajeron productos de cada
-- marca, y cuales (derivado de las ordenes de compra)
CREATE OR REPLACE VIEW v_proveedor_marca AS
SELECT m.id_marca,
       m.mar_nombre                                            AS marca,
       pv.id_proveedor,
       pv.prv_razon_social                                     AS proveedor,
       p.prd_codigo,
       p.prd_nombre,
       COUNT(DISTINCT oc.id_orden_compra)                      AS ordenes,
       SUM(d.dco_cantidad)                                     AS cantidad_base,
       MAX(oc.oc_fecha)                                        AS ultima_compra
FROM marca m
JOIN producto             p  ON p.id_marca         = m.id_marca
JOIN variante             v  ON v.id_producto      = p.id_producto
JOIN detalle_orden_compra d  ON d.id_variante      = v.id_variante
JOIN orden_compra         oc ON oc.id_orden_compra = d.id_orden_compra
JOIN proveedor            pv ON pv.id_proveedor    = oc.id_proveedor
GROUP BY m.id_marca, m.mar_nombre, pv.id_proveedor, pv.prv_razon_social, p.prd_codigo, p.prd_nombre;

