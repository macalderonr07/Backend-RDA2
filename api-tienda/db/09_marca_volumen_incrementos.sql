DECLARE
    v_sistema NUMBER;
    v_x       NUMBER;

    FUNCTION marca(p_nombre IN VARCHAR2) RETURN NUMBER IS
        v_id NUMBER;
    BEGIN
        SELECT MAX(id_marca) INTO v_id FROM marca WHERE mar_nombre = p_nombre;
        IF v_id IS NULL THEN
            INSERT INTO marca (mar_nombre) VALUES (p_nombre) RETURNING id_marca INTO v_id;
        END IF;
        RETURN v_id;
    END;

    PROCEDURE asignar(p_marca IN VARCHAR2, p_codigos IN SYS.ODCIVARCHAR2LIST) IS
        v_marca NUMBER := marca(p_marca);
    BEGIN
        FOR i IN 1 .. p_codigos.COUNT LOOP
            UPDATE producto SET id_marca = v_marca WHERE prd_codigo = p_codigos(i) AND id_marca IS NULL;
        END LOOP;
    END;

    FUNCTION pres(p_variante IN NUMBER, p_desc IN VARCHAR2, p_factor IN NUMBER, p_precio IN NUMBER,
                  p_incremento IN NUMBER DEFAULT 1) RETURN NUMBER IS
        v_pre NUMBER;
    BEGIN
        SELECT MAX(id_presentacion) INTO v_pre
        FROM presentacion WHERE id_variante = p_variante AND pre_descripcion = p_desc;
        IF v_pre IS NULL THEN
            INSERT INTO presentacion (id_variante, pre_descripcion, pre_factor, pre_incremento)
            VALUES (p_variante, p_desc, p_factor, p_incremento)
            RETURNING id_presentacion INTO v_pre;
            INSERT INTO historial_precio (id_presentacion, hpr_precio, hpr_vigente_desde, id_usuario)
            VALUES (v_pre, p_precio, CAST(SYSDATE - 1 AS TIMESTAMP), v_sistema);
        END IF;
        RETURN v_pre;
    END;

    PROCEDURE volumen(p_codigo IN VARCHAR2, p_minima IN NUMBER, p_pct IN NUMBER) IS
        v_prd NUMBER;
        v_n   NUMBER;
    BEGIN
        SELECT id_producto INTO v_prd FROM producto WHERE prd_codigo = p_codigo;
        SELECT COUNT(*) INTO v_n FROM descuento_volumen
        WHERE id_producto = v_prd AND dvo_cantidad_minima = p_minima AND dvo_activo = 1;
        IF v_n = 0 THEN
            INSERT INTO descuento_volumen (id_producto, dvo_cantidad_minima, dvo_porcentaje, id_usuario)
            VALUES (v_prd, p_minima, p_pct, v_sistema);
        END IF;
    END;

