/*==============================================================*/
/* Migracion: marcas, descuento por volumen, incrementos de     */
/*            venta, sintetico por metro y combo unico por color */
/*                                                              */
/*  1. MARCA (opcional por producto): tabla marca y             */
/*     producto.id_marca NULL. Vista v_proveedor_marca (para la */
/*     futura administracion): que proveedores han traido       */
/*     productos de cada marca y cuales, derivado de las        */
/*     ordenes de compra (3FN: no se guarda dos veces).         */
/*  2. INCREMENTO DE VENTA: presentacion.pre_incremento         */
/*     (DEFAULT 1): la cantidad debe ser multiplo de el. El     */
/*     cuero por pie2 se vende de 0.25 en 0.25 (1, 1.25, 1.5,   */
/*     1.75...) con minimo 1; lo demas en cantidades enteras.   */
/*     Lo valida fn_crear_pedido (la garantia real) y la API.   */
/*  3. SINTETICO: Metro, 1/2 metro y 1/4 metro; el rollo queda  */
/*     inactivo (se reactiva cuando se venda por rollo). El     */
/*     inventario sigue en metros: un rollo abierto se vende    */
/*     por metro, igual que el galon y el rollo de cierre.      */
/*  4. DESCUENTO POR VOLUMEN (generico, por producto): tabla    */
/*     descuento_volumen (desde N unidades base, X %). Se       */
/*     aplica como la OFERTA: la linea guarda que regla aplico  */
/*     (detalle_pedido.id_descuento_volumen, la asigna          */
/*     fn_crear_pedido segun lo que lleva el pedido de ese      */
/*     producto, sumando tallas y colores) y la rebaja sale del */
/*     porcentaje en v_detalle_pedido_valor. No usa             */
/*     dpe_descuento, que es la rebaja NEGOCIADA (prohibida en  */
/*     la web). Si una linea se negocia, el valor pactado       */
/*     reemplaza al descuento por volumen. Una regla usada no   */
/*     se modifica: se desactiva y se crea otra.                */
/*     Ejemplo cargado: suelas y plantillas, 8 % desde la       */
/*     docena (12 pares).                                       */
/*  5. COMBO UNICO: un combo ya no apunta a presentaciones de   */
/*     un color, sino a (producto, presentacion, cantidad); el  */
/*     color se elige al agregarlo, entre los que tienen stock  */
/*     en todos sus componentes. "Paquete x 100 m" del cierre   */
/*     pasa a llamarse "Rollo x 100 m".                         */
/*                                                              */
/* Se puede correr mas de una vez.                              */
/*                                                              */
/* Como SYSTEM/SYSDBA en la PDB:                                */
/*   sqlplus system@//localhost:1521/FREEPDB1 @09_marca_volumen_incrementos.sql */
