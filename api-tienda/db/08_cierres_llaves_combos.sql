-- 3. Combos para la tienda: una fila por componente publicado (con su precio
--    vigente y disponibilidad de v_catalogo) + el total de componentes del
--    combo, para descartar combos incompletos.
CREATE OR REPLACE VIEW v_combo_web AS
SELECT c.cmb_codigo                                            AS codigo,
       c.cmb_nombre                                            AS nombre,
       c.cmb_descripcion                                       AS descripcion,
       (SELECT COUNT(*) FROM combo_componente x WHERE x.id_combo = c.id_combo) AS componentes,
       cc.id_presentacion,
       cc.cco_cantidad                                         AS cantidad,
       v.prd_codigo,
       v.prd_nombre,
       v.caracteristicas,
       v.presentacion,
       v.precio_final_con_iva,
       v.disponible,
       v.imagen_url
FROM combo c
JOIN combo_componente cc ON cc.id_combo = c.id_combo
JOIN v_catalogo       v  ON v.id_presentacion = cc.id_presentacion
WHERE c.cmb_publicado = 1;

GRANT SELECT ON produccion.v_combo_web TO ecommerce WITH GRANT OPTION;
GRANT SELECT ON produccion.v_combo_web TO elite_ecommerce;

ALTER SESSION SET CURRENT_SCHEMA = ecommerce;
CREATE OR REPLACE VIEW v_combo_web AS
SELECT * FROM produccion.v_combo_web;
