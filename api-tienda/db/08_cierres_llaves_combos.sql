/*==============================================================*/
/* Migracion: cierres, llaves y COMBOS de productos             */
/*                                                              */
/* Casos de uso del negocio:                                    */
/*  1. CIERRE: se vende el paquete como viene (100 m) o por     */
/*     metros. Inventario en metros: al abrir un paquete el     */
/*     contador de paquetes baja solo (FLOOR(saldo/factor)) y   */
/*     lo abierto queda vendible por metro, igual que el galon. */
/*  2. LLAVES (deslizadores) del cierre: 2 llaves, 1/2 docena,  */
/*     docena, 50 o ciento.                                     */
/*  3. COMBOS: "1 m de cierre + 2 llaves". Un combo es una      */
/*     RECETA de presentaciones con su cantidad. Al agregarlo   */
/*     al carrito se convierte en sus lineas reales, asi el     */
/*     checkout (fn_crear_pedido_desde_carrito), el precio      */
/*     vigente y la validacion de stock siguen siendo los de la */
/*     base, sin una segunda logica de cobro. El precio del     */
/*     combo es la suma de sus componentes.                     */
/*                                                              */
/* Tablas nuevas (nodo produccion, el catalogo es suyo):        */
/*   combo, combo_componente. Vista v_combo_web (y espejo en    */
/*   ecommerce) con una fila por componente PUBLICADO y el      */
/*   total de componentes, para que la API descarte un combo    */
/*   si alguno de sus productos se despublica.                  */
/*                                                              */
/* Se puede correr mas de una vez.                              */
/*                                                              */
/* Como SYSTEM/SYSDBA en la PDB:                                */
/*   sqlplus system@//localhost:1521/FREEPDB1 @08_cierres_llaves_combos.sql */
/*==============================================================*/
SET DEFINE OFF
SET SERVEROUTPUT ON
WHENEVER SQLERROR EXIT FAILURE ROLLBACK

ALTER SESSION SET CURRENT_SCHEMA = produccion;

-- 1. Tablas del combo (solo si no existen)
DECLARE
    v_n NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_n FROM all_tables WHERE owner = 'PRODUCCION' AND table_name = 'COMBO';
    IF v_n = 0 THEN
        EXECUTE IMMEDIATE q'[
            CREATE TABLE produccion.combo (
               id_combo          NUMBER(10)        GENERATED BY DEFAULT ON NULL AS IDENTITY,
               cmb_codigo        VARCHAR2(20 CHAR) NOT NULL,
               cmb_nombre        VARCHAR2(120 CHAR) NOT NULL,
               cmb_descripcion   VARCHAR2(300 CHAR) NULL,
               cmb_publicado     NUMBER(1)         DEFAULT 1 NOT NULL
                  CONSTRAINT ckb_cmb_publicado CHECK (cmb_publicado IN (0, 1)),
               cmb_fecha_creacion TIMESTAMP        DEFAULT LOCALTIMESTAMP NOT NULL,
               CONSTRAINT pk_combo PRIMARY KEY (id_combo),
               CONSTRAINT ak_combo_codigo UNIQUE (cmb_codigo)
            )]';
        EXECUTE IMMEDIATE q'[COMMENT ON TABLE produccion.combo IS
            'Combo de productos (1 m de cierre + 2 llaves): receta de presentaciones. Se vende como sus lineas; su precio es la suma de los componentes.']';
        EXECUTE IMMEDIATE q'[
            CREATE TABLE produccion.combo_componente (
               id_combo          NUMBER(10)     NOT NULL,
               id_presentacion   NUMBER(10)     NOT NULL,
               cco_cantidad      NUMBER(12,3)   NOT NULL
                  CONSTRAINT ckc_cco_cantidad CHECK (cco_cantidad > 0),
               CONSTRAINT pk_combo_componente PRIMARY KEY (id_combo, id_presentacion),
               CONSTRAINT fk_combo_componente_combo FOREIGN KEY (id_combo)
                  REFERENCES produccion.combo (id_combo),
               CONSTRAINT fk_combo_componente_presentacion FOREIGN KEY (id_presentacion)
                  REFERENCES produccion.presentacion (id_presentacion)
            )]';
        EXECUTE IMMEDIATE q'[COMMENT ON COLUMN produccion.combo_componente.cco_cantidad IS
            'Cuantas unidades de la presentacion lleva un combo (en la presentacion, no en unidad base).']';
        DBMS_OUTPUT.PUT_LINE('  + tablas combo y combo_componente');
    END IF;
END;
