-- 2. Linea "Cierres y llaves", productos, presentaciones, stock y combos
DECLARE
    v_sistema NUMBER;
    v_bodega  NUMBER;
    v_color   NUMBER;
    v_raiz    NUMBER;
    v_metro_neg NUMBER; v_metro_caf NUMBER; v_metro_bla NUMBER;
    v_par_neg   NUMBER; v_par_caf   NUMBER; v_par_pla   NUMBER;
    v_x         NUMBER;

    FUNCTION categoria(p_codigo IN VARCHAR2, p_nombre IN VARCHAR2, p_padre IN NUMBER) RETURN NUMBER IS
        v_cat NUMBER;
    BEGIN
        SELECT MAX(id_categoria) INTO v_cat FROM categoria WHERE cat_codigo = p_codigo;
        IF v_cat IS NULL THEN
            INSERT INTO categoria (id_categoria_padre, cat_codigo, cat_nombre)
            VALUES (p_padre, p_codigo, p_nombre)
            RETURNING id_categoria INTO v_cat;
        END IF;
        RETURN v_cat;
    END;

    FUNCTION valor_color(p_valor IN VARCHAR2) RETURN NUMBER IS
        v_val NUMBER;
    BEGIN
        SELECT MAX(id_valor_atributo) INTO v_val
        FROM valor_atributo WHERE id_atributo = v_color AND val_valor = p_valor;
        IF v_val IS NULL THEN
            INSERT INTO valor_atributo (id_atributo, val_valor) VALUES (v_color, p_valor)
            RETURNING id_valor_atributo INTO v_val;
        END IF;
        RETURN v_val;
    END;

    FUNCTION pres(p_variante IN NUMBER, p_desc IN VARCHAR2, p_factor IN NUMBER, p_precio IN NUMBER) RETURN NUMBER IS
        v_pre NUMBER;
    BEGIN
        SELECT MAX(id_presentacion) INTO v_pre
        FROM presentacion WHERE id_variante = p_variante AND pre_descripcion = p_desc;
        IF v_pre IS NULL THEN
            INSERT INTO presentacion (id_variante, pre_descripcion, pre_factor)
            VALUES (p_variante, p_desc, p_factor)
            RETURNING id_presentacion INTO v_pre;
            -- vigente desde ayer: ver 06 (zona horaria del contenedor vs la API)
            INSERT INTO historial_precio (id_presentacion, hpr_precio, hpr_vigente_desde, id_usuario)
            VALUES (v_pre, p_precio, CAST(SYSDATE - 1 AS TIMESTAMP), v_sistema);
        END IF;
        RETURN v_pre;
    END;

    -- Producto con una variante por color; devuelve nada (las presentaciones van aparte)
    PROCEDURE producto(p_codigo IN VARCHAR2, p_nombre IN VARCHAR2, p_cat IN NUMBER, p_unidad IN VARCHAR2,
                       p_uso IN VARCHAR2, p_imagen IN VARCHAR2, p_colores IN SYS.ODCIVARCHAR2LIST) IS
        v_prd NUMBER;
        v_var NUMBER;
        v_val NUMBER;
    BEGIN
        SELECT MAX(id_producto) INTO v_prd FROM producto WHERE prd_codigo = p_codigo;
        IF v_prd IS NOT NULL THEN RETURN; END IF;
        INSERT INTO producto (id_categoria, id_unidad_medida, id_tarifa_iva, prd_codigo, prd_nombre,
                              prd_uso, prd_imagen_url, prd_publicado)
        VALUES (p_cat, p_unidad, '4', p_codigo, p_nombre, p_uso, p_imagen, 1)
        RETURNING id_producto INTO v_prd;
        FOR i IN 1 .. p_colores.COUNT LOOP
            INSERT INTO variante (id_producto, var_sku)
            VALUES (v_prd, p_codigo || '-' || LPAD(i, 2, '0'))
            RETURNING id_variante INTO v_var;
            v_val := valor_color(p_colores(i));
            INSERT INTO variante_valor (id_variante, id_atributo, id_valor_atributo)
            VALUES (v_var, v_color, v_val);
        END LOOP;
        DBMS_OUTPUT.PUT_LINE('  + producto ' || p_codigo);
    END;

    FUNCTION variante_de(p_sku IN VARCHAR2) RETURN NUMBER IS
        v_var NUMBER;
    BEGIN
        SELECT id_variante INTO v_var FROM variante WHERE var_sku = p_sku;
        RETURN v_var;
    END;

    -- Inventario inicial (unidad base), solo si la variante no tiene lotes
    PROCEDURE stock(p_sku IN VARCHAR2, p_cantidad IN NUMBER, p_costo IN NUMBER) IS
        v_var NUMBER := variante_de(p_sku);
        v_n   NUMBER;
        v_mov NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_n FROM lote WHERE id_variante = v_var;
        IF v_n = 0 THEN
            v_mov := fn_registrar_ajuste(v_var, 'INI', p_cantidad, 'Inventario inicial', v_bodega, p_costo);
        END IF;
    END;

    PROCEDURE combo(p_codigo IN VARCHAR2, p_nombre IN VARCHAR2, p_desc IN VARCHAR2,
                    p_comp IN SYS.ODCINUMBERLIST, p_cant IN SYS.ODCINUMBERLIST) IS
        v_cmb NUMBER;
    BEGIN
        SELECT MAX(id_combo) INTO v_cmb FROM combo WHERE cmb_codigo = p_codigo;
        IF v_cmb IS NOT NULL THEN RETURN; END IF;
        INSERT INTO combo (cmb_codigo, cmb_nombre, cmb_descripcion)
        VALUES (p_codigo, p_nombre, p_desc)
        RETURNING id_combo INTO v_cmb;
        FOR i IN 1 .. p_comp.COUNT LOOP
            INSERT INTO combo_componente (id_combo, id_presentacion, cco_cantidad)
            VALUES (v_cmb, p_comp(i), p_cant(i));
        END LOOP;
        DBMS_OUTPUT.PUT_LINE('  + combo ' || p_codigo);
    END;

BEGIN
    SELECT id_usuario INTO v_sistema FROM usuario WHERE usu_correo = 'sistema@comercialelite.local';
    SELECT MAX(id_usuario) INTO v_bodega FROM usuario WHERE usu_correo = 'inventario@comercialelite.local';
    IF v_bodega IS NULL THEN
        RAISE_APPLICATION_ERROR(-20000, 'Falta el usuario de bodega: correr antes 03_inventario_inicial.sql');
    END IF;
    fn_usuario_sesion(v_bodega);
    SELECT id_atributo INTO v_color FROM atributo WHERE atr_nombre = 'Color';

    -- Linea nueva: aparece sola en la portada (v_categoria_web)
    v_raiz := categoria('cierres', 'Cierres y llaves', NULL);
    INSERT INTO categoria_atributo (id_categoria, id_atributo)
    SELECT v_raiz, v_color FROM dual
    WHERE NOT EXISTS (SELECT 1 FROM categoria_atributo WHERE id_categoria = v_raiz AND id_atributo = v_color);

    producto('CE-9001', 'Cierre de nylon N.º 5 por metro', categoria('cierres-1', 'Cierres', v_raiz), 'm',
             'Botas, carteras y chompas de cuero',
             'https://upload.wikimedia.org/wikipedia/commons/b/b6/YKK_Zipper_on_Jeans_close_up.jpg',
             SYS.ODCIVARCHAR2LIST('Negro', 'Café', 'Blanco'));
    producto('CE-9002', 'Llave para cierre N.º 5', categoria('cierres-2', 'Llaves', v_raiz), 'u',
             'Deslizador para cierre de nylon N.º 5',
             'https://thumb.wikimedia.org/wikipedia/commons/thumb/8/83/Zipper_Pullers.jpg/960px-Zipper_Pullers.jpg',
             SYS.ODCIVARCHAR2LIST('Negro', 'Café', 'Plateado'));

    -- Cierre: paquete de 100 m (mas barato por metro) o metro suelto. Precios SIN IVA.
    FOR i IN 1 .. 3 LOOP
        v_x := pres(variante_de('CE-9001-0' || i), 'Paquete × 100 m', 100, 30.00);
        v_x := pres(variante_de('CE-9001-0' || i), 'Metro', 1, 0.35);
    END LOOP;
    v_metro_neg := pres(variante_de('CE-9001-01'), 'Metro', 1, 0.35);
    v_metro_caf := pres(variante_de('CE-9001-02'), 'Metro', 1, 0.35);
    v_metro_bla := pres(variante_de('CE-9001-03'), 'Metro', 1, 0.35);

    -- Llaves: 2, 1/2 docena, docena, 50 o ciento
    FOR i IN 1 .. 3 LOOP
        v_x := pres(variante_de('CE-9002-0' || i), '2 llaves',   2,   0.20);
        v_x := pres(variante_de('CE-9002-0' || i), '1/2 docena', 6,   0.55);
        v_x := pres(variante_de('CE-9002-0' || i), 'Docena',     12,  1.00);
        v_x := pres(variante_de('CE-9002-0' || i), '50 llaves',  50,  3.80);
        v_x := pres(variante_de('CE-9002-0' || i), 'Ciento',     100, 7.00);
    END LOOP;
    v_par_neg := pres(variante_de('CE-9002-01'), '2 llaves', 2, 0.20);
    v_par_caf := pres(variante_de('CE-9002-02'), '2 llaves', 2, 0.20);
    v_par_pla := pres(variante_de('CE-9002-03'), '2 llaves', 2, 0.20);

    -- Inventario en unidad base (metros y unidades), costo por unidad base
    stock('CE-9001-01', 600, 0.22);   -- 6 paquetes
    stock('CE-9001-02', 400, 0.22);   -- 4 paquetes
    stock('CE-9001-03', 200, 0.22);   -- 2 paquetes
    stock('CE-9002-01', 1000, 0.06);
    stock('CE-9002-02', 600, 0.06);
    stock('CE-9002-03', 500, 0.06);

    -- Combos: 1 m de cierre + 2 llaves (un "2 llaves")
    combo('CMB-CIERRE-NEG', 'Combo cierre negro: 1 m + 2 llaves',
          'Un metro de cierre N.º 5 negro con sus dos llaves negras.',
          SYS.ODCINUMBERLIST(v_metro_neg, v_par_neg), SYS.ODCINUMBERLIST(1, 1));
    combo('CMB-CIERRE-CAF', 'Combo cierre café: 1 m + 2 llaves',
          'Un metro de cierre N.º 5 café con sus dos llaves café.',
          SYS.ODCINUMBERLIST(v_metro_caf, v_par_caf), SYS.ODCINUMBERLIST(1, 1));
    combo('CMB-CIERRE-BLA', 'Combo cierre blanco: 1 m + 2 llaves plateadas',
          'Un metro de cierre N.º 5 blanco con dos llaves plateadas.',
          SYS.ODCINUMBERLIST(v_metro_bla, v_par_pla), SYS.ODCINUMBERLIST(1, 1));

    COMMIT;
END;
